const {chromium}=require('playwright');
const path=require('node:path');
const {pathToFileURL}=require('node:url');
(async()=>{
 const browser=await chromium.launch({headless:true});
 const page=await browser.newPage({viewport:{width:390,height:844}});
 const errors=[];page.on('pageerror',err=>errors.push(err.message));
 await page.route('**/firebase-config.js',route=>route.fulfill({body:'window.NONO_FIREBASE_CONFIG={};',contentType:'text/javascript'}));
 const uri=pathToFileURL(path.resolve(__dirname,'../dist/index.html')).href;
 await page.goto(uri);
 await page.locator('#nono-theme-open').waitFor();
 if((await page.locator('#nono-theme-open').innerText()).indexOf('상점')<0)throw Error('Store entry not renamed');
 await page.click('#nono-theme-open');
 await page.locator('#nono-shop-tab-themes').waitFor();
 if(await page.locator('#nono-shop-themes .nono-theme-card').count()!==10)throw Error('Missing existing theme catalog');
 await page.click('#nono-shop-tab-points');
 if(!await page.locator('#nono-shop-points').isVisible()||await page.locator('#nono-shop-themes').isVisible())throw Error('Recharge panel not shown');
 if(await page.locator('#nono-shop-points button:not([disabled])').count())throw Error('Unverified cash purchases are enabled');
 await page.click('#nono-shop-tab-premium');
 if(!await page.locator('#nono-shop-premium').isVisible())throw Error('Ad-free premium panel missing');
 if(await page.locator('#nono-shop-premium button:not([disabled])').count())throw Error('Unverified premium purchase enabled');
 await page.click('#nono-shop-tab-themes');
 await page.evaluate(()=>{
  const s=JSON.parse(localStorage.getItem('nono-daily-preview-v1')||'{}');
  s.points=500;s.ownedThemes=[];
  localStorage.setItem('nono-daily-preview-v1',JSON.stringify(s));
  window.NONO_DAILY_REWARDS.refresh();
  window.NONO_SHOP.refresh();
 });
 await page.locator('#nono-theme-groups').count().catch(()=>0);
 await page.getByRole('button',{name:'오로라 네온 미리보기'}).click();
 await page.locator('#nono-shop-buy-theme').waitFor({state:'visible'});
 if(await page.locator('#nono-shop-buy-theme').isDisabled())throw Error('Earned points cannot buy theme');
 await page.click('#nono-shop-buy-theme');
 const state=await page.evaluate(()=>{
  const s=window.NONO_DAILY_REWARDS.getSnapshot();
  return {points:s.points,owned:s.ownedThemes.includes('aurora'),buttonHidden:document.querySelector('#nono-shop-buy-theme').hidden};
 });
 if(state.points!==200||!state.owned||!state.buttonHidden)throw Error('Theme redeem failed: '+JSON.stringify(state));
 await page.locator('#nono-theme-use').click();
 if(await page.locator('body').getAttribute('data-nono-theme')!=='aurora')throw Error('Purchased theme not applied');
 await page.reload();
 if(await page.locator('body').getAttribute('data-nono-theme')!=='aurora')throw Error('Purchased theme not persisted');
 await page.locator('#nono-theme-open').click();
 const ownedLabel=await page.locator('.nono-theme-card[data-theme-id="aurora"] .nono-theme-price').textContent();
 if(!ownedLabel.includes('보유'))throw Error('Owned theme not marked in shop after reload: '+ownedLabel);
 const noDuplicate=await page.evaluate(()=>window.NONO_DAILY_REWARDS.purchaseTheme('aurora'));
 if(noDuplicate.ok||await page.evaluate(()=>window.NONO_DAILY_REWARDS.getSnapshot().points)!==200)throw Error('Duplicate purchase charged balance');
 if(errors.length)throw Error('Store JavaScript errors: '+errors.join(' | '));
 console.log('NONO unified store: theme purchase, persistence, recharge/premium safety, mobile pass.');
 await browser.close();
})().catch(e=>{console.error(e);process.exit(1)});