/* Generated public-trial smoke test. Uses actual built HTML, not an image mock. */
const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path');
const {pathToFileURL}=require('node:url'),{chromium}=require('playwright');
(async()=>{
 const built=path.resolve(__dirname,'..','dist');
 const index=JSON.parse(fs.readFileSync(path.join(built,'trial-index.json'),'utf8'));
 const snow=index.find(p=>p.id==='winter-snowman-trial-v1');
 assert(snow,'Missing snowman from autogenerated trial index');
 assert.equal(snow.width,59);assert.equal(snow.height,63);
 const html=fs.readFileSync(path.join(built,'trials','winter-snowman-trial-v1.html'),'utf8');
 const raw=html.match(/<script type="application\/json" id="data">([\s\S]*?)<\/script>/);
 assert(raw,'Missing public clue JSON');
 const p=JSON.parse(raw[1]);
 assert.equal(p.rows.length,63);assert.equal(p.cols.length,59);
 const total=lines=>lines.reduce((a,line)=>a+line.reduce((x,y)=>x+y,0),0);
 assert.equal(total(p.rows),1140);assert.equal(total(p.cols),1140);
 assert(!('mask' in p)&&!('packed' in p)&&!('answer' in p),'Public page must not contain private answer');
 assert(html.includes('repeat(59,var(--cell))'),'Trial width not reflected in CSS');
 assert(html.includes("const KEY='nono-trial-'+d.id+'-v1'"),'Save key must be unique to each puzzle');
 const landing=fs.readFileSync(path.join(built,'index.html'),'utf8');
 assert(landing.includes('./trials/winter-snowman-trial-v1.html'),'Trial page must be reachable from home');
 const browser=await chromium.launch({headless:true});
 try{
  const page=await browser.newPage({viewport:{width:1200,height:850}});
  const errors=[];page.on('pageerror',e=>errors.push(e.message));
  await page.goto(pathToFileURL(path.join(built,'trials','winter-snowman-trial-v1.html')).href);
  await page.locator('#matrix .cell').first().waitFor({state:'visible'});
  assert.equal(await page.locator('#matrix .cell').count(),63*59);
  assert.equal(await page.locator('#matrix .row-hint').count(),63);
  assert.equal(await page.locator('#matrix .col-hint').count(),59);
  await page.locator('#matrix .cell').first().click();
  assert(await page.locator('#matrix .cell').first().evaluate(e=>e.classList.contains('filled')));
  await page.locator('#undo').click();
  assert(!await page.locator('#matrix .cell').first().evaluate(e=>e.classList.contains('filled')));
  await page.locator('#redo').click();
  await page.reload();
  await page.locator('#matrix .cell').first().waitFor();
  assert(await page.locator('#matrix .cell').first().evaluate(e=>e.classList.contains('filled')),'Delta log resume failed');
  assert.deepEqual(errors,[],'Browser page errors');
  console.log('PASS 63x59 autogenerated trial: public hints only, exact rows/cols, paint, undo, redo, resume');
 }finally{await browser.close();}
})().catch(e=>{console.error(e);process.exitCode=1;});
